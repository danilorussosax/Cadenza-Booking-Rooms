import type { ChannelSettingsRow, MessagingChannel } from '@/api/messaging';

export interface ChannelDef {
  channel: MessagingChannel;
  label: string;
  helpKey: string;
  /** Campi credenziali necessari (chiave secret + tipo password/text).
   *  `validate` opzionale: tag risolto in `validateField` per bloccare il salva. */
  fields: {
    key: string;
    labelKey: string;
    type: 'text' | 'password';
    placeholder?: string;
    validate?: 'telegramToken';
  }[];
  /** Chiavi credenziali generate dal sistema (non editabili a mano): mostrate
   *  come stato read-only. Per Telegram: webhookSecret (creato da auto-configure). */
  autoGeneratedKeys?: { key: string; labelKey: string }[];
  /** Campi non-secret in `settings` (visibili in chiaro). */
  settingsFields?: { key: string; labelKey: string; placeholder?: string }[];
  setupGuideKey: string;
  /** Telegram: mostra il pannello passaggi guidati + verifica webhook. */
  guided?: boolean;
}

